import { Document, Page, Text, View, StyleSheet } from "@react-pdf/renderer";
import type { ReportTable } from "@/lib/reports/types";

const styles = StyleSheet.create({
  page: { padding: 32, fontSize: 9, fontFamily: "Helvetica", color: "#1a1a1a" },
  headerRow: { flexDirection: "row", justifyContent: "space-between", marginBottom: 16 },
  orgName: { fontSize: 15, fontWeight: 700 },
  muted: { color: "#666666" },
  title: { fontSize: 13, fontWeight: 700, marginBottom: 4, textAlign: "right" },
  table: { borderWidth: 1, borderColor: "#dddddd", marginTop: 12 },
  tableRow: { flexDirection: "row", borderBottomWidth: 1, borderColor: "#eeeeee" },
  tableHeaderRow: { flexDirection: "row", backgroundColor: "#f3f3f3", borderBottomWidth: 1, borderColor: "#dddddd" },
  cell: { flex: 1, padding: 5 },
  cellRight: { flex: 1, padding: 5, textAlign: "right" },
  totalsBlock: { marginTop: 12, alignSelf: "flex-end", width: 280 },
  totalsRow: { flexDirection: "row", justifyContent: "space-between", paddingVertical: 2 },
  footer: { marginTop: 24, fontSize: 8, color: "#888888" },
});

export function ReportDocument({ report }: { report: ReportTable }) {
  const { header, columns, rows, totals } = report;

  return (
    <Document>
      <Page size="A4" orientation={columns.length > 6 ? "landscape" : "portrait"} style={styles.page}>
        <View style={styles.headerRow}>
          <View>
            <Text style={styles.orgName}>{header.organizationName}</Text>
            {header.organizationAddress && <Text style={styles.muted}>{header.organizationAddress}</Text>}
            {header.organizationGstin && <Text style={styles.muted}>GSTIN: {header.organizationGstin}</Text>}
          </View>
          <View>
            <Text style={styles.title}>{report.title.toUpperCase()}</Text>
            {header.projectName && <Text style={styles.muted}>Project: {header.projectName}</Text>}
            {header.clientName && <Text style={styles.muted}>Client: {header.clientName}</Text>}
            <Text style={styles.muted}>Generated: {header.generatedAt}</Text>
          </View>
        </View>

        <View style={styles.table}>
          <View style={styles.tableHeaderRow}>
            {columns.map((col) => (
              <Text key={col.key} style={col.align === "right" ? styles.cellRight : styles.cell}>
                {col.label}
              </Text>
            ))}
          </View>
          {rows.map((row, idx) => (
            <View key={idx} style={styles.tableRow}>
              {columns.map((col) => (
                <Text key={col.key} style={col.align === "right" ? styles.cellRight : styles.cell}>
                  {row[col.key] ?? "—"}
                </Text>
              ))}
            </View>
          ))}
          {rows.length === 0 && (
            <View style={styles.tableRow}>
              <Text style={styles.cell}>No data available.</Text>
            </View>
          )}
        </View>

        {totals && totals.length > 0 && (
          <View style={styles.totalsBlock}>
            {totals.map((t) => (
              <View key={t.label} style={styles.totalsRow}>
                <Text style={styles.muted}>{t.label}</Text>
                <Text>{t.value}</Text>
              </View>
            ))}
          </View>
        )}

        <Text style={styles.footer}>Generated by the studio&apos;s project management system — figures reflect live data at time of export.</Text>
      </Page>
    </Document>
  );
}
